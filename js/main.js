document.addEventListener("DOMContentLoaded", function () {
  if (window.Alfa.i18n) window.Alfa.i18n.init();
  if (window.Alfa.heroReveal) window.Alfa.heroReveal.init();
  if (window.Alfa.lightSource) window.Alfa.lightSource.init();
  if (window.Alfa.glyphField) window.Alfa.glyphField.init();
  if (window.Alfa.reveal) window.Alfa.reveal.init();
  if (window.Alfa.scrollProgress) window.Alfa.scrollProgress.init();
});
